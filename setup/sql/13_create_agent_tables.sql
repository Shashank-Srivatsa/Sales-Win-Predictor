USE DATABASE SALES_WIN_DB;
USE SCHEMA ML;

-- 1. Pipeline Health & Self-Healing Log (Agent 1: Pipeline Watcher)
CREATE TABLE IF NOT EXISTS SALES_WIN_DB.ML.PIPELINE_HEALTH_LOG (
    LOG_ID VARCHAR(50) DEFAULT UUID_STRING(),
    EXECUTION_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PIPELINE_STAGE VARCHAR(100),
    STATUS VARCHAR(20),                      -- 'SUCCESS', 'WARNING', 'FAILED', 'HEALED'
    TESTS_PASSED INT,
    TESTS_FAILED INT,
    CORRUPTED_RECORDS_ISOLATED INT,
    ERROR_DETAILS TEXT,
    INTERVENTION_SUMMARY TEXT
);

-- 2. Deal Strategic Briefs (Agent 2: Deal Strategist)
CREATE TABLE IF NOT EXISTS SALES_WIN_DB.ML.DEAL_STRATEGY_BRIEFS (
    BRIEF_ID VARCHAR(50) DEFAULT UUID_STRING(),
    OPPORTUNITY_ID VARCHAR(50),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    XGB_WIN_PROBABILITY FLOAT,
    LLM_WIN_PROBABILITY FLOAT,
    PROBABILITY_DELTA FLOAT,
    DISAGREEMENT_REASON TEXT,
    TOP_POSITIVE_FACTORS TEXT,
    TOP_NEGATIVE_FACTORS TEXT,
    SIMILAR_HISTORICAL_DEALS_SUMMARY TEXT,
    RECOMMENDED_STRATEGY TEXT,
    STRATEGY_STATUS VARCHAR(30) DEFAULT 'ACTIVE'   -- 'ACTIVE', 'REVIEWED', 'DISMISSED'
);

-- 3. Proactive Business Action Log (Agent 3: Action Agent)
CREATE TABLE IF NOT EXISTS SALES_WIN_DB.ML.ACTION_LOG (
    ACTION_ID VARCHAR(50) DEFAULT UUID_STRING(),
    OPPORTUNITY_ID VARCHAR(50),
    DISPATCH_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ALERT_TYPE VARCHAR(50),                  -- 'HIGH_VALUE_RISK', 'NEGOTIATION_STALL', 'WIN_DISCREPANCY'
    DEAL_VALUE FLOAT,
    CURRENT_PROBABILITY_BAND VARCHAR(20),
    DAYS_IN_NEGOTIATION INT,
    ASSIGNED_AGENT_ID VARCHAR(50),
    ALERT_RECIPIENT VARCHAR(255),
    ALERT_CONTENT TEXT,
    DISPATCH_CHANNEL VARCHAR(50),            -- 'SLACK', 'EMAIL', 'WEBHOOK', 'CONSOLE'
    DISPATCH_STATUS VARCHAR(20)              -- 'SENT', 'FAILED', 'SIMULATED'
);
